"""Writes network_labs/native_windows_icons.js: the Fluent UI System Icons the Windows pages use, taken from Microsoft's
MIT-licensed @fluentui/svg-icons package (https://github.com/microsoft/fluentui-system-icons).

    npm pack @fluentui/svg-icons && tar -xzf fluentui-svg-icons-*.tgz
    python3 tools/build_windows_icons.py package/icons

Outline icons follow the text colour (fill="currentColor"); colour icons keep their own gradients."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'network_labs' / 'native_windows_icons.js'

COLOUR = ['settings', 'home', 'wifi', 'person', 'paint_brush', 'apps', 'clock', 'globe', 'game_chat', 'shield', 'arrow_sync',
          'laptop', 'document', 'data_area', 'add_circle', 'image', 'video']
OUTLINE = ['search', 'chevron_right', 'chevron_up', 'chevron_down', 'arrow_left', 'arrow_right', 'arrow_up', 'speaker_2', 'alert',
           'airplane', 'weather_moon', 'accessibility', 'copy', 'power', 'person', 'grid', 'arrow_sort', 'arrow_clockwise', 'add_circle',
           'paint_brush', 'settings', 'window_console', 'folder', 'document', 'hard_drive', 'delete', 'desktop', 'globe', 'info', 'key',
           'data_usage', 'shield_lock', 'shield', 'gauge', 'call', 'router', 'network_check', 'globe_prohibited', 'cut', 'clipboard_paste',
           'rename', 'share', 'more_horizontal', 'home', 'image', 'music_note_2', 'video', 'arrow_download', 'battery_saver',
           'brightness_high', 'bluetooth', 'open', 'window_new', 'lock_closed', 'laptop', 'desktop_mac', 'panel_left', 'edit', 'star',
           'apps', 'clock', 'arrow_sync', 'keyboard']


def inner(text):
    """(viewBox size, the drawing) of one icon file."""
    size = int(re.search(r'viewBox="0 0 (\d+) \d+"', text).group(1))
    body = text[text.index('>') + 1:text.rindex('</svg>')]
    return size, body


def main(icons):
    found = {}
    for name in COLOUR:
        found[name + ':c'] = inner((icons / f'{name}_20_color.svg').read_text(encoding='utf-8'))
    for name in OUTLINE:
        found[name] = inner((icons / f'{name}_20_regular.svg').read_text(encoding='utf-8'))
    lines = ['/* Fluent UI System Icons, (c) Microsoft Corporation, MIT License (assets/FLUENT-ICONS-LICENSE.txt).',
             ' * Generated by tools/build_windows_icons.py from the @fluentui/svg-icons package: do not edit by hand. */',
             "'use strict';",
             'window.nlFluent = ' + json.dumps(found, ensure_ascii=False, separators=(',', ':')) + ';', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: {len(found)} icons')


if __name__ == '__main__':
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path('package/icons'))
